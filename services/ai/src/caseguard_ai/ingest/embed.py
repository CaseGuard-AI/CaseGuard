"""Chunk and embed the corpus (#18): ``corpus.documents`` -> ``corpus.chunks``.

    uv run python -m caseguard_ai.ingest.embed [--rebuild] [--limit N] [--embedder bge-m3|hash]
    pnpm data:embed

It is a job, safe to stop and re-run at any point:

1. **Check** ``corpus.corpus_meta``. A corpus embedded with another model or revision is refused
   (mixing vectors from two models makes retrieval meaningless) unless ``--rebuild`` is given,
   which deletes every chunk first.
2. **Chunk** every document that has no chunks, has chunks from another chunker version, or
   changed after it was chunked (the loader bumps ``updated_at``). Its old chunks are replaced.
3. **Embed** every chunk that has no vector yet, in batches. A stopped run leaves some chunks
   without vectors; the next run carries on with those.
4. **Record** the model, revision, chunker settings and input snapshots in ``corpus_meta``.

The full-text column (``tsv``) is generated by Postgres from the chunk text, so it is always
filled. Runs as caseguard_ai (ADR-0002). Document contents are never logged.
"""

from __future__ import annotations

import argparse
import sys
import time
from collections.abc import Callable
from dataclasses import dataclass
from typing import Any

from pgvector.sqlalchemy import Vector
from sqlalchemy import (
    Connection,
    Engine,
    and_,
    bindparam,
    create_engine,
    delete,
    exists,
    func,
    insert,
    or_,
    select,
    true,
    update,
)
from sqlalchemy.dialects.postgresql import insert as pg_insert

from caseguard_ai.config import IngestSettings
from caseguard_ai.db.tables import EMBEDDING_DIMS, FTS_CONFIG, chunks, corpus_meta, documents
from caseguard_ai.ingest.chunker import CHUNKER_VERSION, ChunkerSettings, chunk_document
from caseguard_ai.ingest.embedder import Embedder, get_embedder

DOCUMENT_BATCH = 50


class ModelMismatch(Exception):
    """The corpus was embedded with a different model; mixing them would break retrieval."""


@dataclass
class EmbedReport:
    documents_chunked: int = 0
    chunks_written: int = 0
    chunks_embedded: int = 0
    documents_without_chunks: int = 0
    seconds: float = 0.0

    def line(self) -> str:
        return (
            f"chunked {self.documents_chunked} documents into {self.chunks_written} chunks, "
            f"embedded {self.chunks_embedded} chunks in {self.seconds:.0f}s"
            + (
                f"; {self.documents_without_chunks} documents gave no chunks"
                if self.documents_without_chunks
                else ""
            )
        )


# ── corpus_meta ─────────────────────────────────────────────────────────────────────────────


def check_meta(conn: Connection, embedder: Embedder, *, rebuild: bool) -> None:
    """Refuse a different model, unless rebuilding; on a rebuild, delete every chunk."""
    meta = conn.execute(select(corpus_meta)).mappings().first()
    built_with = (
        None
        if meta is None or meta["embedding_model"] is None
        else (meta["embedding_model"], meta["embedding_revision"])
    )
    wanted = (embedder.model_id, embedder.revision)
    if built_with is not None and built_with != wanted and not rebuild:
        raise ModelMismatch(
            f"the corpus was embedded with {built_with[0]}@{built_with[1]}, not "
            f"{wanted[0]}@{wanted[1]}. Re-run with --rebuild to re-embed everything, "
            "or set EMBEDDING_MODEL / EMBEDDING_REVISION back."
        )
    if embedder.dims != EMBEDDING_DIMS:
        raise ModelMismatch(f"{embedder.model_id} gives {embedder.dims} dims, not {EMBEDDING_DIMS}")
    if rebuild:
        conn.execute(delete(chunks))
    _write_meta(conn, embedder, built=False, chunker=None)


def _write_meta(
    conn: Connection, embedder: Embedder, *, built: bool, chunker: ChunkerSettings | None
) -> None:
    values: dict[str, Any] = {
        "id": 1,
        "embedding_model": embedder.model_id,
        "embedding_revision": embedder.revision,
        "embedding_dims": embedder.dims,
        "embedding_normalized": embedder.normalized,
        "fts_config": FTS_CONFIG,
        # Until a run finishes, the corpus may be partly embedded.
        "built_at": func.now() if built else None,
    }
    if chunker is not None:
        values["chunker_version"] = CHUNKER_VERSION
        values["chunker_settings"] = chunker.as_dict()
        values["input_snapshots"] = list(
            conn.execute(
                select(documents.c.snapshot)
                .where(documents.c.snapshot.is_not(None))
                .distinct()
                .order_by(documents.c.snapshot)
            ).scalars()
        )
    stmt = pg_insert(corpus_meta).values(values)
    conn.execute(stmt.on_conflict_do_update(index_elements=[corpus_meta.c.id], set_=values))


# ── chunking ────────────────────────────────────────────────────────────────────────────────


def _stale_documents() -> Any:
    """Documents whose chunks are missing, from another chunker version, or older than the text."""
    has_chunks = exists().where(chunks.c.document_id == documents.c.id)
    outdated = exists().where(
        and_(
            chunks.c.document_id == documents.c.id,
            or_(
                chunks.c.chunker_version != CHUNKER_VERSION,
                chunks.c.created_at < documents.c.updated_at,
            ),
        )
    )
    return or_(~has_chunks, outdated)


def chunk_pending(
    engine: Engine,
    settings: ChunkerSettings,
    report: EmbedReport,
    *,
    limit: int | None = None,
    progress: Callable[[str], None] = lambda _: None,
) -> None:
    done: set[Any] = set()  # documents that gave no chunks are not retried within one run
    while limit is None or report.documents_chunked < limit:
        take = DOCUMENT_BATCH
        if limit is not None:
            take = min(take, limit - report.documents_chunked)
        with engine.begin() as conn:
            rows = conn.execute(
                select(
                    documents.c.id,
                    documents.c.kind,
                    documents.c.title,
                    documents.c.full_text,
                    documents.c.headnote_only,
                    documents.c.third_party,
                )
                .where(_stale_documents(), documents.c.id.not_in(done) if done else true())
                .order_by(documents.c.id)
                .limit(take)
            ).all()
            if not rows:
                return
            ids = [r.id for r in rows]
            conn.execute(delete(chunks).where(chunks.c.document_id.in_(ids)))
            new_rows: list[dict[str, Any]] = []
            for row in rows:
                pieces = chunk_document(
                    kind=row.kind,
                    title=row.title,
                    full_text=row.full_text,
                    headnote_only=row.headnote_only,
                    settings=settings,
                )
                if not pieces:
                    report.documents_without_chunks += 1
                    done.add(row.id)
                new_rows.extend(
                    {
                        "document_id": row.id,
                        "ordinal": piece.ordinal,
                        "locator": piece.locator,
                        "section_id": piece.section_id,
                        "text": piece.text,
                        "token_count": piece.token_count,
                        "headnote_only": row.headnote_only,
                        "third_party": row.third_party,
                        "chunker_version": CHUNKER_VERSION,
                    }
                    for piece in pieces
                )
            if new_rows:
                conn.execute(insert(chunks), new_rows)
        report.documents_chunked += len(rows)
        report.chunks_written += len(new_rows)
        progress(f"chunked {report.documents_chunked} documents ({report.chunks_written} chunks)")


# ── embedding ───────────────────────────────────────────────────────────────────────────────


def embed_pending(
    engine: Engine,
    embedder: Embedder,
    report: EmbedReport,
    *,
    batch_size: int = 64,
    progress: Callable[[str], None] = lambda _: None,
) -> None:
    write = (
        update(chunks)
        .where(chunks.c.id == bindparam("chunk_id"))
        .values(embedding=bindparam("vector", type_=Vector(EMBEDDING_DIMS)))
    )
    with engine.connect() as conn:
        remaining = conn.execute(
            select(func.count()).select_from(chunks).where(chunks.c.embedding.is_(None))
        ).scalar_one()
    while True:
        with engine.begin() as conn:
            rows = conn.execute(
                select(chunks.c.id, chunks.c.text)
                .where(chunks.c.embedding.is_(None))
                .order_by(chunks.c.id)
                .limit(batch_size)
            ).all()
            if not rows:
                return
            vectors = embedder.embed([r.text for r in rows])
            conn.execute(
                write,
                [{"chunk_id": r.id, "vector": v} for r, v in zip(rows, vectors, strict=True)],
            )
        report.chunks_embedded += len(rows)
        progress(f"embedded {report.chunks_embedded} of {remaining} chunks")


# ── the job ─────────────────────────────────────────────────────────────────────────────────


def run(
    engine: Engine,
    embedder: Embedder,
    *,
    rebuild: bool = False,
    limit: int | None = None,
    settings: ChunkerSettings | None = None,
    batch_size: int = 64,
    progress: Callable[[str], None] = lambda _: None,
) -> EmbedReport:
    settings = settings or ChunkerSettings()
    report = EmbedReport()
    started = time.monotonic()
    with engine.begin() as conn:
        check_meta(conn, embedder, rebuild=rebuild)
    chunk_pending(engine, settings, report, limit=limit, progress=progress)
    embed_pending(engine, embedder, report, batch_size=batch_size, progress=progress)
    with engine.begin() as conn:
        _write_meta(conn, embedder, built=True, chunker=settings)
    report.seconds = time.monotonic() - started
    return report


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description="Chunk and embed corpus.documents")
    parser.add_argument(
        "--rebuild", action="store_true", help="delete every chunk and re-embed with this model"
    )
    parser.add_argument("--limit", type=int, help="chunk at most N documents this run")
    parser.add_argument(
        "--embedder",
        default="bge-m3",
        choices=["bge-m3", "hash"],
        help="hash is a test embedder: never build a real corpus with it",
    )
    parser.add_argument("--batch-size", type=int, default=None, help="chunks per embedding batch")
    args = parser.parse_args([a for a in (sys.argv[1:] if argv is None else argv) if a != "--"])
    cfg = IngestSettings()
    embedder = get_embedder(
        args.embedder,
        cfg.embedding_model,
        cfg.embedding_revision,
        device=cfg.embedding_device or None,
        batch_size=cfg.embedding_batch_size,
    )
    engine = create_engine(cfg.sqlalchemy_url)
    try:
        report = run(
            engine,
            embedder,
            rebuild=args.rebuild,
            limit=args.limit,
            batch_size=args.batch_size or max(cfg.embedding_batch_size * 4, 16),
            progress=lambda line: print(line, file=sys.stderr, flush=True),
        )
    except ModelMismatch as exc:
        print(f"refusing: {exc}", file=sys.stderr)
        return 2
    finally:
        engine.dispose()
    print(report.line())
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
